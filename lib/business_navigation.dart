  // ===========================================================================
  // INSTANT PDF POS INVOICE / RECEIPT GENERATOR
  // ===========================================================================
  Future<void> _generatePosInvoicePdf(BusinessTxModel tx, TransactionProvider provider) async {
    try {
      final doc = pw.Document();
      doc.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a5,
          margin: const pw.EdgeInsets.all(24),
          build: (pw.Context ctx) => pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text('FINBLEND BUSINESS POS', style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold)),
                      pw.Text(
                        provider.userOrganization.isNotEmpty ? provider.userOrganization : 'Official POS Invoice / Voucher',
                        style: const pw.TextStyle(fontSize: 11),
                      ),
                    ],
                  ),
                  pw.Text('RECEIPT #${tx.id.substring(math.max(0, tx.id.length - 6))}', style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold)),
                ],
              ),
              pw.Divider(height: 20),
              pw.Text('Date & Time: ${tx.date}', style: const pw.TextStyle(fontSize: 10)),
              pw.Text('Transaction Type: ${tx.type.toUpperCase()}', style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold)),
              pw.Text('Issued By: ${provider.userName} (${provider.cloudEmail})', style: const pw.TextStyle(fontSize: 10)),
              pw.SizedBox(height: 16),
              pw.TableHelper.fromTextArray(
                headers: ['Description / Item Details', 'Category', 'Amount (BDT)'],
                data: [
                  [tx.title, tx.type, 'BDT ${tx.amount.toStringAsFixed(2)}'],
                ],
              ),
              pw.SizedBox(height: 16),
              pw.Align(
                alignment: pw.Alignment.centerRight,
                child: pw.Text(
                  'TOTAL AMOUNT: BDT ${tx.amount.toStringAsFixed(2)}',
                  style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold),
                ),
              ),
              pw.Spacer(),
              pw.Divider(),
              pw.Center(
                child: pw.Text('Thank you for your business! • Generated by FinBlend Cloud POS', style: const pw.TextStyle(fontSize: 9)),
              ),
            ],
          ),
        ),
      );

      final Uint8List bytes = await doc.save();
      await Printing.sharePdf(bytes: bytes, filename: 'FinBlend_Invoice_${tx.id}.pdf');
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('PDF Invoice Error: $e')));
      }
    }
  }

