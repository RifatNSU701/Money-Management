  // ===========================================================================
  // SMART POS CHECKOUT SHEET (AUTO STOCK DEDUCTION & CUSTOMER DUE INTEGRATION)
  // ===========================================================================
  void _showSmartPosCheckoutSheet(BuildContext context, {required String initialType}) {
    final provider = context.read<TransactionProvider>();
    String selectedType = initialType;
    String selectedProductId = 'custom';
    int quantity = 1;
    final titleCtrl = TextEditingController();
    final amountCtrl = TextEditingController();

    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: const Color(0xFF161616),
      shape: const RoundedRectangleBorder(borderRadius: BorderRadius.vertical(top: Radius.circular(28))),
      builder: (ctx) => StatefulBuilder(
        builder: (context, setSheetState) {
          ProductModel? chosenProduct;
          if (selectedProductId != 'custom') {
            final idx = provider.products.indexWhere((p) => p.id == selectedProductId);
            if (idx != -1) chosenProduct = provider.products[idx];
          }

          return Padding(
            padding: EdgeInsets.only(bottom: MediaQuery.of(ctx).viewInsets.bottom + 24, left: 24, right: 24, top: 24),
            child: SingleChildScrollView(
              child: Column(
                mainAxisSize: MainAxisSize.min,
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  const Text('Smart POS Entry & Inventory Sync', style: TextStyle(color: Colors.white, fontSize: 19, fontWeight: FontWeight.bold), textAlign: TextAlign.center),
                  const SizedBox(height: 14),
                  Row(
                    children: ['Sale', 'Purchase', 'Expense'].map((t) {
                      final isSel = selectedType == t;
                      return Expanded(
                        child: Padding(
                          padding: const EdgeInsets.symmetric(horizontal: 4.0),
                          child: ChoiceChip(
                            label: Center(child: Text(t, style: TextStyle(color: isSel ? Colors.black : Colors.white, fontWeight: FontWeight.bold))),
                            selected: isSel,
                            selectedColor: Colors.tealAccent,
                            backgroundColor: const Color(0xFF1E1E1E),
                            showCheckmark: false,
                            onSelected: (_) => setSheetState(() => selectedType = t),
                          ),
                        ),
                      );
                    }).toList(),
                  ),
                  const SizedBox(height: 14),

                  if (selectedType != 'Expense' && provider.products.isNotEmpty) ...[
                    const Text('Link Inventory Product (Auto-Updates Stock):', style: TextStyle(color: Colors.grey, fontSize: 12, fontWeight: FontWeight.bold)),
                    const SizedBox(height: 8),
                    Wrap(
                      spacing: 8,
                      runSpacing: 8,
                      children: [
                        ChoiceChip(
                          label: const Text('Custom Entry', style: TextStyle(fontSize: 11, fontWeight: FontWeight.bold)),
                          selected: selectedProductId == 'custom',
                          selectedColor: Colors.tealAccent,
                          labelStyle: TextStyle(color: selectedProductId == 'custom' ? Colors.black : Colors.white),
                          backgroundColor: const Color(0xFF1E1E1E),
                          showCheckmark: false,
                          onSelected: (_) => setSheetState(() => selectedProductId = 'custom'),
                        ),
                        ...provider.products.map((p) {
                          final isSel = selectedProductId == p.id;
                          return ChoiceChip(
                            label: Text('${p.name} (Stock: ${p.stock} • ৳${p.price.toStringAsFixed(0)})', style: const TextStyle(fontSize: 11, fontWeight: FontWeight.bold)),
                            selected: isSel,
                            selectedColor: Colors.tealAccent,
                            labelStyle: TextStyle(color: isSel ? Colors.black : Colors.white),
                            backgroundColor: const Color(0xFF1E1E1E),
                            showCheckmark: false,
                            onSelected: (_) => setSheetState(() {
                              selectedProductId = p.id;
                              titleCtrl.text = '${p.name} (x$quantity)';
                              amountCtrl.text = (p.price * quantity).toStringAsFixed(0);
                            }),
                          );
                        }),
                      ],
                    ),
                    if (chosenProduct != null) ...[
                      const SizedBox(height: 10),
                      Row(
                        mainAxisAlignment: MainAxisAlignment.center,
                        children: [
                          IconButton(
                            icon: const Icon(Icons.remove_circle_outline, color: Colors.tealAccent),
                            onPressed: () {
                              if (quantity > 1) {
                                setSheetState(() {
                                  quantity--;
                                  titleCtrl.text = '${chosenProduct!.name} (x$quantity)';
                                  amountCtrl.text = (chosenProduct.price * quantity).toStringAsFixed(0);
                                });
                              }
                            },
                          ),
                          Text('Qty: $quantity', style: const TextStyle(color: Colors.white, fontSize: 16, fontWeight: FontWeight.bold)),
                          IconButton(
                            icon: const Icon(Icons.add_circle_outline, color: Colors.tealAccent),
                            onPressed: () {
                              setSheetState(() {
                                quantity++;
                                titleCtrl.text = '${chosenProduct!.name} (x$quantity)';
                                amountCtrl.text = (chosenProduct.price * quantity).toStringAsFixed(0);
                              });
                            },
                          ),
                        ],
                      ),
                    ],
                    const SizedBox(height: 10),
                  ],

                  TextField(
                    controller: titleCtrl,
                    style: const TextStyle(color: Colors.white),
                    decoration: InputDecoration(
                      labelText: 'Item / Description',
                      labelStyle: const TextStyle(color: Colors.grey),
                      filled: true,
                      fillColor: const Color(0xFF1E1E1E),
                      border: OutlineInputBorder(borderRadius: BorderRadius.circular(16), borderSide: BorderSide.none),
                    ),
                  ),
                  const SizedBox(height: 12),
                  TextField(
                    controller: amountCtrl,
                    keyboardType: TextInputType.number,
                    style: const TextStyle(color: Colors.white, fontWeight: FontWeight.bold),
                    decoration: InputDecoration(
                      labelText: 'Total Amount (৳)',
                      labelStyle: const TextStyle(color: Colors.grey),
                      filled: true,
                      fillColor: const Color(0xFF1E1E1E),
                      border: OutlineInputBorder(borderRadius: BorderRadius.circular(16), borderSide: BorderSide.none),
                    ),
                  ),
                  const SizedBox(height: 20),
                  ElevatedButton(
                    style: ElevatedButton.styleFrom(
                      backgroundColor: Colors.tealAccent,
                      foregroundColor: Colors.black,
                      padding: const EdgeInsets.symmetric(vertical: 16),
                      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
                    ),
                    onPressed: () {
                      final title = titleCtrl.text.trim();
                      final amt = double.tryParse(amountCtrl.text.trim()) ?? 0.0;
                      if (title.isEmpty || amt <= 0) return;

                      if (chosenProduct != null) {
                        if (selectedType == 'Sale' && chosenProduct.stock < quantity) {
                          ScaffoldMessenger.of(context).showSnackBar(
                            SnackBar(backgroundColor: Colors.redAccent, content: Text('Only ${chosenProduct.stock} units of ${chosenProduct.name} available in stock!')),
                          );
                          return;
                        }
                        final int newStock = selectedType == 'Sale'
                            ? math.max(0, chosenProduct.stock - quantity)
                            : (chosenProduct.stock + quantity);
                        provider.saveProduct(
                          id: chosenProduct.id,
                          name: chosenProduct.name,
                          price: chosenProduct.price,
                          stock: newStock,
                        );
                      }

                      provider.saveBusinessTx(title: title, type: selectedType, amount: amt);
                      Navigator.pop(ctx);
                    },
                    child: Text('Save $selectedType & Sync Cloud', style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16)),
                  ),
                ],
              ),
            ),
          );
        },
      ),
    );
  }

