                  child: Column(
                    children: [
                      Row(
                        children: [
                          Container(
                            padding: const EdgeInsets.all(12),
                            decoration: BoxDecoration(
                              color: (isLow ? Colors.redAccent : Colors.tealAccent).withValues(alpha: 0.14),
                              borderRadius: BorderRadius.circular(14),
                            ),
                            child: Icon(Icons.inventory_2_outlined, color: isLow ? Colors.redAccent : Colors.tealAccent),
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Text(p.name, style: const TextStyle(color: Colors.white, fontSize: 16, fontWeight: FontWeight.bold)),
                                const SizedBox(height: 3),
                                Text(
                                  'Unit Price: ৳ ${p.price.toStringAsFixed(0)} • Total Value: ৳ ${(p.price * p.stock).toStringAsFixed(0)}',
